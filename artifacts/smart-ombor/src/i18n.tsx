const dictionaries: Record<Lang, Record<TKey, string>> = { uz, ru };

export function readStoredLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'ru' || stored === 'uz') return stored;
  } catch { /* ignore */ }
  return 'uz';
}

type Vars = Record<string, string | number>;

function interpolate(template: string, vars?: Vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (key in vars ? String(vars[key]) : `{${key}}`));
}

export function translate(lang: Lang, key: TKey, vars?: Vars) {
  const template = dictionaries[lang][key] ?? dictionaries.uz[key] ?? key;
  return interpolate(template, vars);
}

// Numbers: full precision, thin-space thousands grouping, identical in both languages.
const numberFormatter = (digits: number) => new Intl.NumberFormat('ru-RU', { maximumFractionDigits: digits, minimumFractionDigits: 0 });
export function formatNumber(value: number | null | undefined, digits = 0) {
  if (value == null || Number.isNaN(value)) return '—';
  return numberFormatter(digits).format(value).replace(/\u202f/g, '\u00a0');
}
export function formatMoney(lang: Lang, value: number | null | undefined) {
  if (value == null || Number.isNaN(value)) return '—';
  return `${formatNumber(Math.round(value))}\u00a0${translate(lang, 'common.currency')}`;
}

const pad = (n: number) => String(n).padStart(2, '0');
function toDate(value: string | Date | number | null | undefined): Date | null {
  if (value == null || value === '') return null;
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}
export function formatDate(value: string | Date | number | null | undefined) {
  if (typeof value === 'string') {
    const day = value.trim().slice(0, 10);
    if (/^\d{4}-\d{2}-\d{2}$/.test(day)) {
      const [year, month, date] = day.split('-');
      return `${date}.${month}.${year}`;
    }
  }
  const d = toDate(value);
  return d ? `${pad(d.getDate())}.${pad(d.getMonth() + 1)}.${d.getFullYear()}` : '—';
}
export function formatTime(value: string | Date | number | null | undefined) {
  const d = toDate(value);
  return d ? `${pad(d.getHours())}:${pad(d.getMinutes())}` : '—';
}
export function formatDateTime(value: string | Date | number | null | undefined) {
  const d = toDate(value);
  return d ? `${formatDate(d)} ${formatTime(d)}` : '—';
}
export function formatShortDay(lang: Lang, value: string | Date | number | null | undefined) {
  const d = toDate(value);
  if (!d) return '—';
  return `${pad(d.getDate())}.${pad(d.getMonth() + 1)}`;
}
export function weekdayShort(lang: Lang, value: string | Date | number) {
  const d = toDate(value);
  if (!d) return '';
  return translate(lang, 'date.weekdays').split(',')[d.getDay()];
}
export function longToday(lang: Lang, date = new Date()) {
  const weekday = translate(lang, 'date.weekdaysLong').split(',')[date.getDay()];
  return `${weekday}, ${formatDate(date)}`;
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey, vars?: Vars) => string;
  fmt: (value: number | null | undefined, digits?: number) => string;
  money: (value: number | null | undefined) => string;
  date: (value: string | Date | number | null | undefined) => string;
  dateTime: (value: string | Date | number | null | undefined) => string;
  time: (value: string | Date | number | null | undefined) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    fmt: formatNumber,
    money: (v) => formatMoney(lang, v),
    date: formatDate,
    dateTime: formatDateTime,
    time: formatTime,
  }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
